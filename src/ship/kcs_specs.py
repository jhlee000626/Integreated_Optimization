def get_froude_number(v_knots: float) -> float:
    """선속(knots)으로부터 Froude Number 계산"""
    v_ms = v_knots * 0.514444
    return v_ms / math.sqrt(KCS_HULL["g"] * KCS_HULL["Lpp"])
